"""Turns one CBT zip from cbttape.org into a zigi managed git repo.
Shared by process-local-cbtzips.py (all of them) and process-one-cbt.py (just the one).

What zigi wants from a repo (see ZIGICKOT and ZIGI.EXEC in github.com/zigi/zigi):
    - every dataset is a directory (PO) or file (PS) in the root of the repo, in UPPERCASE
    - every dataset is listed in .zigi/dsn, the rest is ignored. So lowercase things (docs, zips) are safe
    - PDS directories are flat, with members having no extension
    - .zigi/<PDS> has the ISPF stats per member
    - binary stuff is listed by its exact path in .gitattributes (or PDS/* if all members are binary)

Nested XMIs are received recursively. A member ASM in nested XMI XMITIP becomes dataset XMITIP.ASM
Stuff that can't be rebuilt from flat files (RECFM=U, binary PS) stays an XMI, in the repo as NAME.XMI

Author:
    Wizard of z/OS
"""
from ftplib import FTP, error_perm
import datetime
import fnmatch
import glob
import json
import os
import re
import shutil
import subprocess
import tempfile
import zipfile

import xmi

FTPSERVER = 'ftp.cbttape.org'

docmimetypes = ['application/msword', 'application/epub+zip', 'application/pdf', 'application/vnd.openxmlformats-officedocument.wordprocessingml.document','application/vnd.oasis.opendocument.text','application/vnd.ms-powerpoint','application/vnd.ms-excel','application/vnd.openxmlformats-officedocument.presentationml.presentation','application/java-archive','message/rfc822']

# Same list zigi primes a new repo with
binarypatterns = ['*.docm','*.docx','*.doc','*.dotx','*.pdf','*.epub','*.mobi','*.azw3','*.jpg','*.jpeg','*.png','*.gif','*.zip','*.gzip','*.tz','*.z','*.Z','*.pax','*.ppt','*.pptx','*.xls','*.xlsx','*.xlsm','*.obj','*.bin','*.tiff']

# What zigi itself writes for a binary element, ZIGICKOT does a grep for the uppercase BINARY
BINARY = 'git-encoding=BINARY binary'

DSNHEADER = """# ZIGI dsn-file
# This file needs to be here.
# Don't edit unless you know what you're doing :)
#
# record format is (case insensitive):
#
# Position - description
#
# 1 - directory name which will be prefixed by the
#     defined HLQ to create the z/OS dataset
#     (* defines the default)
# 2 - PS or PO (dataset organization)
#     PS for a flat file
#     PO for a directory and thus a partitioned dataset
# 3 - record format (FB or VB)
# 4 - lrecl
# 5 - blksize
#     0 is allowed if system determined blksize is enabled
# 6 - extension (optional - if used then no period)
#     file extension to be used for PDS members in USS
#
# Default DSORG and DCB info
* PO FB 80 32720
"""


class CbtError(Exception):
    """This CBT file can't be turned into a repo"""


class Repo:
    """What we collect while filling up a repo"""
    def __init__(self, path, name, main):
        self.path  = path
        self.name  = name
        self.main  = main # name of the PDS with the 'main' XMI
        self.dsn   = {}   # dataset -> 'PO FB 80 32720'
        self.stats = {}   # PDS -> lines for .zigi/PDS
        self.log   = []

    def logit(self, line):
        self.log.append(f'{datetime.datetime.now()} - {line}\n')

    def dataset(self, member, pdsname):
        name = member if pdsname == self.main else f'{pdsname}.{member}'
        # zigi reads a line in .zigi/dsn that starts with # as a comment
        if name[0] == '#':
            name = ('@' if not os.path.exists(f'{self.path}/@{name[1:]}') else '$') + name[1:]
        return name


def istext(file):
    # git converts UTF-8 -> ibm-1047, so needs valid UTF-8 within latin-1 range and no NULs
    with open(file, 'rb') as f:
        data = f.read()
    if b'\x00' in data:
        return False
    try:
        text = data.decode('utf-8')
    except UnicodeDecodeError:
        return False
    return all(ord(c) <= 0xFF for c in text)


def gitattrpath(relpath):
    # No leading slash here! zigi compares this with PDS/MEMBER
    p = ''.join('\\' + c if c in '*?[]\\' else c for c in relpath.replace(os.sep, '/'))
    if p[0] in '#!':
        p = '\\' + p
    if ' ' in p or '"' in p:
        p = '"' + p.replace('\\', '\\\\').replace('"', '\\"') + '"'
    return p


def attribfile(path, pdss=()):
    lines = ("# This .gitattributes file is autogenerated with cbt2git\n"
             "*                 git-encoding=utf-8 zos-working-tree-encoding=ibm-1047\n"
             ".gitattributes    git-encoding=utf-8 zos-working-tree-encoding=iso8859-1\n"
             ".gitignore        git-encoding=utf-8 zos-working-tree-encoding=ibm-1047\n"
             ".zigi/*           git-encoding=utf-8 zos-working-tree-encoding=ibm-1047\n")
    lines += ''.join(f'{p} binary\n' for p in binarypatterns)
    lines += f'*.xmi {BINARY}\n*.XMI {BINARY}\n'

    # Anything else git can't convert to ibm-1047 on z/OS (load modules, gifs, tar.gz...) gets its own line
    binaries = []
    for root, dirs, files in os.walk(path):
        if '.git' in dirs:
            dirs.remove('.git')
        dirs.sort()
        for f in sorted(files):
            full = os.path.join(root, f)
            if not istext(full):
                binaries.append(os.path.relpath(full, path).replace(os.sep, '/'))

    for pds in pdss:
        members = os.listdir(os.path.join(path, pds))
        inpds = [b for b in binaries if b.startswith(pds + '/')]
        if members and len(inpds) == len(members):
            lines += f'{gitattrpath(pds)}/* {BINARY}\n'
            binaries = [b for b in binaries if b not in inpds]

    for b in binaries:
        # NAME.XMI is a dataset to zigi so it needs its own line, the rest is covered by the patterns
        if b.endswith('.xmi') or any(fnmatch.fnmatchcase(os.path.basename(b), p) for p in binarypatterns):
            continue
        lines += f'{gitattrpath(b)} {BINARY}\n'

    with open(f'{path}/.gitattributes', 'w') as a:
        a.write(lines)


def statline(member, ispf, lines=None):
    """Line for .zigi/PDS, looks just like what zigi generates"""
    if not ispf or not ispf.get('createdate'):
        return f"{member:<8}\n"
    created = ispf['createdate'].split('T')[0][2:].replace('-', '/')
    modified, modtime = created, '00:00:00'
    if ispf.get('modifydate'):
        modified = ispf['modifydate'].split('T')[0][2:].replace('-', '/')
        modtime  = ispf['modifydate'].split('T')[1].split('.')[0]
    vv, mm = ispf['version'].split('.')
    cur, init, mod = ispf['lines'], ispf['newlines'], ispf.get('modlines', 0)
    if lines is not None:
        cur, init, mod = lines, lines, 0
    return f"{member:<8} {created} {modified} {int(vv):02d} {int(mm):02d} {modtime} {cur:>5} {init:>5} {mod:>5} {ispf.get('user') or 'CBT2GIT'}\n"


def placeholder(repo, pdsname, member, ispf, *text):
    """The member in the PDS telling where the real thing went"""
    bar = f"# +{'-' * 55}+\n"
    body = [f"# |{t.center(55)}|\n" for t in ('CBT2GIT DETECTED THIS MEMBER WAS NOT A TEXT MEMBER',) + text]
    with open(f"{repo.path}/{pdsname}/{member}", 'w') as f:
        f.writelines([bar] + body + [bar])
    repo.stats[pdsname].append(statline(member, ispf, len(body) + 2))


def extract(xmifile, into):
    """De-xmi to the folder, returns the parsed info and the name of the dataset in there"""
    obj = xmi.open_file(xmifile, quiet=True)
    obj.set_output_folder(into)
    obj.set_quiet(True)
    obj.extract_all()
    info = json.loads(obj.get_json())
    return info, next(iter(info['file']))


def dcb(info, dsn):
    """dsorg, recfm, lrecl and blksize as stored by whoever did the TRANSMIT"""
    records = [r for r in info['INMR02'].values() if r.get('INMDSNAM') == dsn] or list(info['INMR02'].values())
    r = records[0]
    recfm = r.get('INMRECFM') or 'FB'
    if not re.fullmatch(r'[FVU][BSAM]*', recfm):
        recfm = 'FB'
    return r.get('INMDSORG', 'PS'), recfm, r.get('INMLRECL', 80), r.get('INMBLKSZ', 0)


def add_members(repo, pdsname, info, dsn, srcdir):
    """Every member of the PDS in srcdir ends up in the right place in the repo"""
    folder = f'{repo.path}/{pdsname}'
    os.makedirs(folder, exist_ok=True)
    repo.stats[pdsname] = []
    onext = {f.split('.')[0]: f for f in os.listdir(srcdir)}
    prefix = '' if pdsname == repo.main else pdsname + '.'
    for member, member_info in info['file'][dsn]['members'].items():
        if member not in onext:
            repo.logit(f'** ALERT {repo.name} ** {dsn}({member}) not extracted, skipping')
            continue
        src      = f'{srcdir}/{onext[member]}'
        mimetype = member_info.get('mimetype', 'application/octet-stream')
        ext      = member_info.get('extension') or '.bin'
        ispf     = member_info.get('ispf')

        if mimetype == 'application/xmit':
            add_nested_xmi(repo, pdsname, member, src, ispf, mimetype)

        elif mimetype in docmimetypes:
            place = f'docs/{prefix}{member}{ext}'
            os.makedirs(f'{repo.path}/docs', exist_ok=True)
            shutil.copyfile(src, f'{repo.path}/{place}')
            repo.logit(f'Found {member}{ext} ({mimetype}) in {dsn}, moved to {repo.name}/{place}')
            placeholder(repo, pdsname, member, ispf, 'IT CONTAINED MIME-TYPE', mimetype, 'STORED AS', f'{repo.name}/{place}')

        elif mimetype == 'application/zip' and unzipped(repo, src, f'zips/{prefix}{member}'):
            repo.logit(f'Found {member}{ext} ({mimetype}) in {dsn}, unzipped to {repo.name}/zips/{prefix}{member}')
            placeholder(repo, pdsname, member, ispf, 'IT CONTAINED MIME-TYPE', mimetype, 'UNZIPPED TO', f'{repo.name}/zips/{prefix}{member}')

        else:
            # text is fine as a member, and everything else too: zigi can do binary members in a PDS
            shutil.copyfile(src, f'{folder}/{member}')
            repo.stats[pdsname].append(statline(member, ispf))
            repo.logit(f'Found {member}{ext} ({mimetype}) in {dsn}, moved to {pdsname}/{member}')


def unzipped(repo, src, place):
    target = f'{repo.path}/{place}'
    try:
        with zipfile.ZipFile(src, 'r') as inner_zip:
            inner_zip.extractall(target)
    except Exception as e:
        # This happens in CBT432 : zipfile.BadZipFile: Bad CRC-32 for file 'VB40016.DLL'
        # This happens in CBT990 : zipfile.BadZipFile: File is not a zip file (for DEVTIPS@.zip)
        repo.logit(f'  - {place}: {e}, kept as member')
        shutil.rmtree(target, ignore_errors=True)
        return False
    return True


def add_nested_xmi(repo, pdsname, member, src, ispf, mimetype):
    """An XMI inside a PDS. Becomes a dataset of its own, and we go deeper if there's more XMI in there"""
    name  = repo.dataset(member, pdsname)
    toplevel = pdsname == repo.main
    with tempfile.TemporaryDirectory() as tmp:
        try:
            info, dsn = extract(src, tmp)
            dsorg, recfm, lrecl, blksize = dcb(info, dsn)
        except Exception as e:
            # for 982, the XMI is 'broken' ?
            repo.logit(f'** ALERT {repo.name} ** {pdsname}/{member} De-XMI error: {e}')
            keep_xmi(repo, pdsname, member, src, ispf, name, 'IT COULD NOT BE RECEIVED')
            return

        members = info['file'][dsn].get('members')
        if dsorg == 'PO' and members and recfm[0] != 'U':
            add_members(repo, name, info, dsn, f'{tmp}/{dsn}')
            repo.dsn[name] = f'PO {recfm} {lrecl} {blksize}'
            where = 'NESTED IN ITS PARENT'
            if toplevel:
                # Original XMI stays around too. The deeper ones are in this one anyway
                shutil.copyfile(src, f'{repo.path}/{name}.xmi')
                where = f'{repo.name}/{name}.xmi'
            repo.logit(f'Found {member} (XMI of {dsn}) in {pdsname}, received to {repo.name}/{name}')
            placeholder(repo, pdsname, member, ispf, 'IT WAS AN XMI OF', dsn, 'RECEIVED TO', f'{repo.name}/{name}', 'THE ORIGINAL XMI IS', where)
            return

        seqs = glob.glob(f'{glob.escape(tmp)}/{glob.escape(dsn)}*')
        if dsorg == 'PS' and len(seqs) == 1 and os.path.isfile(seqs[0]) and istext(seqs[0]):
            shutil.copyfile(seqs[0], f'{repo.path}/{name}')
            repo.dsn[name] = f'PS {recfm} {lrecl} {blksize}'
            repo.logit(f'Found {member} (XMI of {dsn}) in {pdsname}, received to {repo.name}/{name}')
            placeholder(repo, pdsname, member, ispf, 'IT WAS AN XMI OF', dsn, 'RECEIVED TO', f'{repo.name}/{name}')
            return

        keep_xmi(repo, pdsname, member, src, ispf, name, f'IT WAS AN XMI OF RECFM={recfm} {dsorg} DATA', dsn)


def keep_xmi(repo, pdsname, member, src, ispf, name, *why):
    """Stays an XMI. As a dataset to zigi: on z/OS you can RECEIVE it and have the real thing"""
    shutil.copyfile(src, f'{repo.path}/{name}.XMI')
    repo.dsn[f'{name}.XMI'] = 'PS FB 80 3120'
    repo.logit(f'Stored {pdsname}/{member} as {repo.name}/{name}.XMI')
    placeholder(repo, pdsname, member, ispf, *why, 'XMI STORED AS', f'{repo.name}/{name}.XMI')


def clear_tree(path):
    """We generate it all again, so anything that's gone from the CBT file is gone from the repo"""
    for entry in os.listdir(path):
        if entry in ('.git', 'cbt2git.log'):
            continue
        full = os.path.join(path, entry)
        if os.path.isdir(full) and not os.path.islink(full):
            shutil.rmtree(full)
        else:
            os.remove(full)


def write_readme(repo):
    # The @FILEnnn is the description of the CBT file
    about = "No @FILE in PDS?\n"
    files = glob.glob(f'{glob.escape(repo.path)}/{glob.escape(repo.main)}/@FIL*')
    if len(files) == 1:
        with open(files[0], errors='replace') as f:
            about = f.read()
    else:
        repo.logit('No @FILExxx or @FILxxxx detected, creating README.md without extra info')
    with open(f'{repo.path}/README.md', 'w') as readme:
        readme.write(f"# {repo.name}\nConverted to GitHub via [cbt2git](https://github.com/wizardofzos/cbt2git)\n")
        readme.write("This is still a work in progress. GitHub repos will be deleted and created during this period...\n")
        readme.write(f"~~~~~~~~~~~~~~~~\n\n{about}~~~~~~~~~~~~~~~~\n\n")


def write_zigi(repo):
    os.makedirs(f'{repo.path}/.zigi', exist_ok=True)
    with open(f'{repo.path}/.zigi/dsn', 'w') as dsnfile:
        dsnfile.write(DSNHEADER)
        dsnfile.writelines(f'{name} {repo.dsn[name]}\n' for name in sorted(repo.dsn))
    for pds, lines in repo.stats.items():
        with open(f'{repo.path}/.zigi/{pds}', 'w') as ispffile:
            ispffile.writelines(sorted(lines))


def convert(zippath, repopath, reponame):
    """Fill the working tree of the repo with what's in the CBT zip. Returns the loglines."""
    cbtnum = int(reponame[3:])
    with tempfile.TemporaryDirectory() as tmp:
        try:
            with zipfile.ZipFile(zippath, 'r') as zip_ref:
                contents = zip_ref.infolist()
                if len(contents) != 1:
                    raise CbtError(f'{zippath} should have one file, found {[c.filename for c in contents]}')
                zip_ref.extractall(tmp)
        except zipfile.BadZipFile as e:
            raise CbtError(f'{zippath} is a bad zip: {e}')
        try:
            info, dsn = extract(f'{tmp}/{contents[0].filename}', tmp)
            dsorg, recfm, lrecl, blksize = dcb(info, dsn)
        except Exception as e:
            # FILE001 and friends are no XMI
            raise CbtError(f'{zippath} has {contents[0].filename} but De-XMI failed: {e}')
        if dsorg != 'PO' or not info['file'][dsn].get('members'):
            raise CbtError(f'No PDS in {contents[0].filename}')

        # Only now we know we've got something, so now we can clear out the old
        clear_tree(repopath)
        repo = Repo(repopath, reponame, f'FILE{cbtnum:03d}')
        repo.logit(f'Initialized conversion of {reponame}')
        repo.logit(f'Received {dsn} from {contents[0].filename}')
        add_members(repo, repo.main, info, dsn, f'{tmp}/{dsn}')
        repo.dsn[repo.main] = f'PO {recfm} {lrecl} {blksize}'
    write_readme(repo)
    write_zigi(repo)
    attribfile(repopath, [d for d, how in repo.dsn.items() if how.startswith('PO')])
    return repo.log


def git(repopath, *args):
    return subprocess.run(['git', '-C', repopath, *args], capture_output=True, text=True)


def sync_local(repopath, remote=None):
    """Make sure there's a local repo, up to date with the one on GitHub if we have that"""
    if not os.path.isdir(f'{repopath}/.git'):
        os.makedirs(repopath, exist_ok=True)
        if remote is not None:
            res = subprocess.run(['git', 'clone', '--quiet', remote.ssh_url, repopath], capture_output=True, text=True)
            if res.returncode != 0:
                raise CbtError(f'Cloning {remote.ssh_url} failed: {res.stderr}')
        else:
            git(repopath, 'init', '--quiet')
        if git(repopath, 'rev-parse', '--verify', '--quiet', 'HEAD').returncode != 0:
            git(repopath, 'symbolic-ref', 'HEAD', 'refs/heads/main')
    elif remote is not None:
        if git(repopath, 'remote', 'get-url', 'origin').returncode != 0:
            git(repopath, 'remote', 'add', 'origin', remote.ssh_url)
        # Working tree is all generated, a run that died halfway shouldn't be in the way
        git(repopath, 'reset', '--hard', '--quiet')
        res = git(repopath, 'fetch', '--quiet', 'origin')
        if res.returncode != 0:
            raise CbtError(f'Fetching {remote.ssh_url} failed: {res.stderr}')
        if git(repopath, 'rev-parse', '--verify', '--quiet', 'origin/main').returncode == 0:
            res = git(repopath, 'merge', '--ff-only', '--quiet', 'origin/main')
            if res.returncode != 0:
                raise CbtError(f'{repopath} has diverged from GitHub: {res.stderr}')


def commit(repopath, reponame, loglines):
    """Commit what's in the working tree, returns False if there was nothing new"""
    git(repopath, 'add', '--all')
    if git(repopath, 'diff', '--cached', '--quiet').returncode == 0:
        return False
    with open(f'{repopath}/cbt2git.log', 'a+') as dalog:
        dalog.writelines(loglines)
    git(repopath, 'add', 'cbt2git.log')
    if git(repopath, 'rev-parse', '--verify', '--quiet', 'HEAD').returncode != 0:
        msg = f'{reponame} : Initial commit'
    else:
        msg = f'Updates from cbttape.org ({datetime.datetime.now().strftime("%Y-%m-%d")})'
    res = git(repopath, 'commit', '--quiet', '-m', msg)
    if res.returncode != 0:
        raise CbtError(f'Commit in {repopath} failed: {res.stderr}')
    return True


def update_repo(zippath, repos, remote=None):
    """Create or update the local repo for this CBT zip. Returns (repopath, changed, loglines)"""
    reponame = os.path.basename(zippath).split('.')[0]
    repopath = os.path.join(repos, reponame)
    sync_local(repopath, remote)
    loglines = convert(zippath, repopath, reponame)
    return repopath, commit(repopath, reponame, loglines), loglines


def connect(configfile='config.yml'):
    """Returns the Github object and the organization we work on"""
    # No store user/pass in scripts lol
    # Get token via https://github.com/settings/tokens/
    import yaml
    from github import Github, GithubException
    try:
        with open(configfile, 'r') as f:
            config = yaml.safe_load(f)
        token, name = config['github']['token'], config['github']['name']
    except (OSError, KeyError, TypeError) as e:
        raise CbtError(f'Need a {configfile} with github: token: and name:, see config-example.yml ({e!r})')
    github = Github(token)
    try:
        return github, github.get_organization(name)
    except GithubException as e:
        raise CbtError(f'GitHub says no to token/organization {name}: {e.status} {e.data}')


def get_remote(me, reponame):
    """The GitHub repo, or None if it's not there yet"""
    from github import GithubException
    try:
        return me.get_repo(reponame)
    except GithubException as e:
        if e.status == 404:
            return None
        raise


def push(me, repopath, reponame, remote, description):
    """Push to GitHub, creates the repo over there if that's needed"""
    if remote is None:
        remote = me.create_repo(reponame, private=False, description=description)
    if git(repopath, 'remote', 'get-url', 'origin').returncode != 0:
        git(repopath, 'remote', 'add', 'origin', remote.ssh_url)
    res = git(repopath, 'push', '--quiet', '-u', 'origin', 'main')
    if res.returncode != 0:
        raise CbtError(f'Push of {reponame} failed: {res.stderr}')
    return remote


def get_toc(ftp):
    """Parses UPDATESTOC.txt. Returns {number: (path on the ftp server, comment)}"""
    raw = bytearray()
    ftp.retrbinary('RETR pub/updates/UPDATESTOC.txt', raw.extend)
    toc = {}
    for line in raw.decode('latin-1').splitlines():
        found = re.match(r'//\*\+file\s*(\d+):\s+(.*)\*(#?)\s+\S', line, re.IGNORECASE)
        if found:
            num, comment, updated = found.groups()
            toc[int(num)] = (f"pub/{'updates' if updated else 'cbt'}/CBT{num}.zip", comment.strip())
    return toc


def download_cbt(cbtnum, stage):
    """Get just this one from cbttape.org. Returns (path to the zip in stage, comment from the TOC)"""
    ftp = FTP(FTPSERVER)
    ftp.login() # per default anonymous :)
    toc = get_toc(ftp)
    if cbtnum not in toc:
        raise CbtError(f'There is no CBT file {cbtnum} in UPDATESTOC.txt')
    path, comment = toc[cbtnum]
    os.makedirs(stage, exist_ok=True)
    target = f"{stage}/{path.split('/')[-1]}"
    # Saw some in the TOC that were somewhere else
    other = path.replace('pub/cbt/', 'pub/updates/') if 'pub/cbt/' in path else path.replace('pub/updates/', 'pub/cbt/')
    for candidate in (path, other):
        try:
            with open(target + '.part', 'wb') as fp:
                ftp.retrbinary(f'RETR {candidate}', fp.write)
            os.replace(target + '.part', target)
            ftp.quit()
            return target, comment
        except error_perm:
            continue
    os.remove(target + '.part')
    raise CbtError(f'CBT file {cbtnum} is in the TOC, but not on {FTPSERVER}')
